const suffixes: Set<string> = new _Set(MULTI_LABEL);

function isIp(hostname: string): boolean {
	return /^[\d.]+$/.test(hostname) || hostname.includes(":");
}

/** true if `domain` is itself a public suffix (cookies can't be scoped to it) */
export function isPublicSuffix(domain: string): boolean {
	if (isIp(domain)) return false;
	if (suffixes.has(domain)) return true;
	// every bare TLD is a public suffix. single-label hosts like "localhost"
	// are too, but cookie code allows Domain= equal to the host itself
	return !domain.includes(".");
}

/** the registrable domain (eTLD+1) of a hostname; IPs and single labels are their own site */
export function registrableDomain(hostname: string): string {
	hostname = hostname.toLowerCase();
	if (hostname.endsWith(".")) hostname = hostname.slice(0, -1);
	if (isIp(hostname)) return hostname;
	const labels = hostname.split(".");
	if (labels.length <= 2) return hostname;

	// longest known multi-label suffix wins; otherwise the TLD is the suffix
	for (let i = 1; i < labels.length - 1; i++) {
		const candidate = labels.slice(i).join(".");
		if (suffixes.has(candidate)) return labels.slice(i - 1).join(".");
	}
	return labels.slice(-2).join(".");
}
